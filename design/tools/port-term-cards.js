// Ports the 11 term cards from the design canvas into the prototype (STATE "Build it", 2026-10-16).
//   node design/tools/port-term-cards.js
// Reads design/canvas/Term*.dc.html and writes
//   prototype/src/render/termCardData.ts   each card's scene markup and its title-and-meaning markup, as strings
//   prototype/src/termCards.css            each card's own CSS, scoped under .tc-<id> with its @keyframes renamed tc-<id>-<name>
// Both outputs are generated: edit the canvas file and run this again, or edit the output by hand and stop running it.
// What stays out: the copied round-screen backdrop, the close button and "Got it" (render/termCards.ts draws those once), and the
// shared .term / .bm rules (screens.css has them).

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "..");
const canvas = path.join(root, "design", "canvas");
const CARDS = {
  slam: "TermSlam", guard: "TermGuard", mend: "TermMend", expose: "TermExpose", exposed: "TermExposed", frozen: "TermFrozen",
  burn: "TermBurn", shield: "TermShield", chain: "TermChain", backfire: "TermBackfire", fatigue: "TermFatigue",
};

/** Splits a stylesheet into top-level blocks: comments, at-rules (with nested braces) and plain rules. */
function blocks(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    if (/\s/.test(css[i])) { i++; continue; }
    if (css.startsWith("/*", i)) { i = css.indexOf("*/", i) + 2; continue; }
    const open = css.indexOf("{", i);
    let depth = 0, j = open;
    for (; j < css.length; j++) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}" && --depth === 0) break;
    }
    out.push({ head: css.slice(i, open).trim(), body: css.slice(open + 1, j) });
    i = j + 1;
  }
  return out;
}

const SHARED = (head) => head === "*" || head === "body" || /^\.term\b/.test(head) || /^\.bm\b/.test(head) || head === "@keyframes bossPulse";

const properties = new Map(); // @property blocks are global; keep one copy of each
let css = "/* Generated by design/tools/port-term-cards.js from design/canvas/Term*.dc.html. Do not edit by hand unless you stop running the script. */\n";
let ts = "// Generated by design/tools/port-term-cards.js from design/canvas/Term*.dc.html. Do not edit by hand unless you stop running the script.\n// Each card: `scene` is the animated picture, `text` is the title row and the meaning. The shell (close, Got it) is render/termCards.ts.\n\nexport const TERM_CARD_DATA: Record<string, { scene: string; text: string }> = {\n";

for (const [id, file] of Object.entries(CARDS)) {
  const src = fs.readFileSync(path.join(canvas, file + ".dc.html"), "utf8").replace(/\r\n/g, "\n");
  const style = src.slice(src.indexOf("<style>") + 7, src.indexOf("</style>"));
  const kept = blocks(style).filter((b) => !SHARED(b.head));

  const kfNames = kept.filter((b) => b.head.startsWith("@keyframes")).map((b) => b.head.split(/\s+/)[1]);
  const renameAnimations = (text) =>
    text.replace(/(animation(?:-name)?\s*:)([^;"}]*)/g, (_, prop, val) => {
      let v = val;
      for (const n of kfNames) v = v.replace(new RegExp("(^|[\\s,])" + n + "(?=[\\s,]|$)", "g"), `$1tc-${id}-${n}`);
      return prop + v;
    });

  css += `\n/* ---------- ${file} ---------- */\n`;
  for (const b of kept) {
    if (b.head.startsWith("@property")) {
      if (!properties.has(b.head)) properties.set(b.head, b.body.trim());
      continue;
    }
    if (b.head.startsWith("@keyframes")) {
      css += `@keyframes tc-${id}-${b.head.split(/\s+/)[1]} {${b.body}}\n`;
      continue;
    }
    const sel = b.head.split(",").map((s) => `.tc-${id} ${s.trim()}`).join(", ");
    css += `${sel} {${renameAnimations(b.body)}}\n`;
  }

  const sceneFrom = src.indexOf("<!-- the scene");
  const sceneStart = src.indexOf("\n", sceneFrom) + 1;
  const textFrom = src.indexOf("<!-- name and meaning -->");
  const sceneHtml = src.slice(sceneStart, textFrom);
  const textStart = src.indexOf("\n", textFrom) + 1;
  const textEnd = src.indexOf("<button", textStart);
  const strip = (h) => renameAnimations(h.replace(/<!--[\s\S]*?-->/g, "")).replace(/\n\s*\n/g, "\n").trim();
  ts += `  ${id}: {\n    scene: ${JSON.stringify(strip(sceneHtml))},\n    text: ${JSON.stringify(strip(src.slice(textStart, textEnd)))},\n  },\n`;
}
ts += "};\n";

let props = "";
for (const [head, body] of properties) props += `${head} { ${body} }\n`;
css = css.replace("\n/* ----------", `\n${props}\n/* ----------`);

fs.writeFileSync(path.join(root, "prototype", "src", "termCards.css"), css);
fs.writeFileSync(path.join(root, "prototype", "src", "render", "termCardData.ts"), ts);
console.log(`ported ${Object.keys(CARDS).length} cards, ${properties.size} @property rule(s), ${css.length} bytes of CSS, ${ts.length} bytes of markup`);
